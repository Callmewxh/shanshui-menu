#!/usr/bin/env node
// Canvas 导出不能直接绘制桌面壳/离线环境中的相对路径图片，否则画布会被标记为 tainted。
// 将导出需要的本地位图编译为 data URI，运行时只使用这些同源内嵌数据。
const fs = require('fs');
const path = require('path');
const root = path.resolve(__dirname, '..');
const files = [];
function collect(dir, prefix) {
  if (!fs.existsSync(dir)) return;
  for (const name of fs.readdirSync(dir).sort()) {
    if (!/\.(png|jpe?g|webp)$/i.test(name)) continue;
    files.push({ key: `${prefix}/${name}`, path: path.join(dir, name) });
  }
}
collect(path.join(root, 'assets', 'export'), 'assets/export');
collect(path.join(root, 'data', 'img'), 'data/img');
const mime = (file) => /\.png$/i.test(file) ? 'image/png' : /\.webp$/i.test(file) ? 'image/webp' : 'image/jpeg';
const entries = files.map(({ key, path: file }) => `${JSON.stringify(key)}:${JSON.stringify(`data:${mime(file)};base64,${fs.readFileSync(file).toString('base64')}`)}`);
fs.writeFileSync(path.join(root, 'assets', 'export-assets.js'), `/* generated by tools/build-export-assets.js */\nwindow.__EXPORT_ASSETS__={${entries.join(',')}};\n`);
console.log(`✓ 已内嵌 ${files.length} 个 Canvas 导出资源`);
